"""Generates lib/src/common/charset_tables.dart from Python's codec tables.

Dart only ships ASCII, Latin-1 and UTF-8 codecs. Tables for the other
single-byte character sets referenced by ECI values, for Shift_JIS (JIS X 0213)
and for GB2312 (QR Hanzi mode) are generated here.

Run from the package root with `python3 tool/generate_charsets.py`, then
`dart tool/prepare_submit.dart` to format the output.
"""

import base64
import unicodedata

CODECS = [
    ('cp437', 'cp437'),
    ('iso8859_2', 'iso8859_2'),
    ('iso8859_3', 'iso8859_3'),
    ('iso8859_4', 'iso8859_4'),
    ('iso8859_5', 'iso8859_5'),
    ('iso8859_6', 'iso8859_6'),
    ('iso8859_7', 'iso8859_7'),
    ('iso8859_8', 'iso8859_8'),
    ('iso8859_9', 'iso8859_9'),
    ('iso8859_10', 'iso8859_10'),
    ('iso8859_11', 'iso8859_11'),
    ('iso8859_13', 'iso8859_13'),
    ('iso8859_14', 'iso8859_14'),
    ('iso8859_15', 'iso8859_15'),
    ('iso8859_16', 'iso8859_16'),
    ('cp1250', 'cp1250'),
    ('cp1251', 'cp1251'),
    ('cp1252', 'cp1252'),
    ('cp1256', 'cp1256'),
]


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(r.capitalize() for r in rest)


def dart_char(c):
    """A character as it can appear in a Dart single-quoted string."""
    if (ord(c) < 0x80 or c in "'\\$\ufffd"
            or unicodedata.category(c)[0] in 'CMZ'):
        return '\\u{%X}' % ord(c)
    return c


def dart_string(text):
    return "'%s'" % ''.join(dart_char(c) for c in text)


def encode_table(codes):
    """Base64 of the zigzag varint deltas between consecutive code units.

    Read by decodeCharsetTable in lib/src/common/charsets.dart. This is
    several times smaller than a string literal once compiled to JavaScript.
    """
    data = bytearray()
    previous = 0
    for code in codes:
        delta = code - previous
        previous = code
        value = (delta << 1) ^ (delta >> 31)
        while value >= 0x80:
            data.append((value & 0x7F) | 0x80)
            value >>= 7
        data.append(value)
    encoded = base64.b64encode(bytes(data)).decode()
    return ["'%s'" % encoded[i:i + 72] for i in range(0, len(encoded), 72)]


def append_table(out, name, codes):
    out.append('const %s =' % name)
    out.extend('    ' + line for line in encode_table(codes))
    out[-1] += ';'
    out.append('')


def main():
    out = [
        '// GENERATED by tool/generate_charsets.py. Do not edit.',
        '',
        '// Code points for the bytes 0x80-0xFF of single-byte character sets.',
        '// The bytes 0x00-0x7F are the same as ASCII. 0xFFFD marks undefined bytes.',
        '',
    ]
    for dart_name, codec in CODECS:
        for i in range(0x80):
            assert bytes([i]).decode(codec) == chr(i), (codec, i)
        high = [ord(bytes([i]).decode(codec, errors='replace'))
                for i in range(0x80, 0x100)]
        out.append('const %sHigh = <int>[' % camel(dart_name))
        out.append(', '.join('0x%04X' % c for c in high) + ',')
        out.append('];')
        out.append('')
    # GB2312: 94 code units for each lead byte 0xA1-0xF7, indexed by the
    # trail byte 0xA1-0xFE. 0xFFFD marks undefined byte pairs.
    gb2312 = []
    for lead in range(0xA1, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                c = bytes([lead, trail]).decode('gb2312')
            except UnicodeDecodeError:
                c = '\ufffd'
            assert len(c) == 1 and ord(c) >= 0x80, (lead, trail, c)
            gb2312.append(ord(c))
    append_table(out, 'gb2312TableData', gb2312)
    # Shift_JIS double-byte characters: 189 code units for each lead byte
    # 0x81-0x9F and 0xE0-0xFC, indexed by the trail byte 0x40-0xFC. Characters
    # outside the BMP, or made of several code points, are 0xFFFD in the table
    # and listed in sjisExtras.
    extras = {}
    sjis = []
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
        for trail in range(0x40, 0xFD):
            try:
                c = bytes([lead, trail]).decode('shift_jis_2004')
            except UnicodeDecodeError:
                c = '\ufffd'
            if len(c) != 1 or ord(c) > 0xFFFF:
                extras[(lead << 8) | trail] = c
                c = '\ufffd'
            sjis.append(ord(c))
    append_table(out, 'sjisTableData', sjis)
    out.append('const sjisExtras = <int, String>{')
    for code, text in sorted(extras.items()):
        out.append('  0x%04X: %s,' % (code, dart_string(text)))
    out.append('};')
    out.append('')
    with open('lib/src/common/charset_tables.dart', 'w') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
